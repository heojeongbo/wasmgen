import type { ResolvedInput } from '../../model/config.js';
import type { ResultType } from '../../model/value-types.js';

const bindingTypes: Record<ResultType, string> = {
  i32: 'i32', u32: 'u32', f64: 'f64', bool: 'bool', string: 'String', void: '()',
  'i32[]': 'Box<[i32]>', 'u32[]': 'Box<[u32]>', 'f64[]': 'Box<[f64]>',
};

export function rustBridge(input: ResolvedInput): string {
  const functions = input.exports.map((fn, index) => {
    const parameters = fn.params.map((param, i) => `arg${i}: ${bindingTypes[param.type]}`).join(', ');
    const args = fn.params.map((param, i) => `arg${i}${param.type.endsWith('[]') ? '.into_vec()' : ''}`).join(', ');
    const result = bindingTypes[fn.result];
    const signature = fn.error ? `Result<${result}, JsValue>` : result;
    const call = `wasmgen_native::${fn.symbol}(${args})`;
    const invoke = fn.error ? `${call}.map_err(|error| JsValue::from_str(&error.to_string()))?` : call;
    const value = fn.result.endsWith('[]') ? 'value.into_boxed_slice()' : 'value';
    return `#[wasm_bindgen]
pub fn wasmgen_call_${index}(${parameters}) -> ${signature} {
    let value = ${invoke};
    ${fn.error ? `Ok(${value})` : value}
}`;
  });
  return `// Code generated by wasmgen. DO NOT EDIT.
use wasm_bindgen::prelude::*;

${functions.join('\n\n')}
`;
}
