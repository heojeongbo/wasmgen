import type { ResolvedInput } from '../../model/config.js';
import type { ResultType } from '../../model/value-types.js';

function goType(type: ResultType): string {
  if (type.endsWith('[]')) return `[]${goType(type.slice(0, -2) as ResultType)}`;
  return { i32: 'int32', u32: 'uint32', f64: 'float64', bool: 'bool', string: 'string', void: 'void' }[type as Exclude<ResultType, `${string}[]`>];
}
export function goBridge(mod: ResolvedInput, importPath: string): string {
  const quote = String.fromCharCode(96);
  const bindings = mod.exports.map((fn) => {
    const params = fn.params.map((param, i) => `      var arg${i} ${goType(param.type)}
      if err := json.Unmarshal(args[${i}], &arg${i}); err != nil {
        return nil, fmt.Errorf("decode ${param.name}: %w", err)
      }`).join('\n');
    const call = `native.${fn.symbol}(${fn.params.map((_, i) => `arg${i}`).join(', ')})`;
    const invoke = fn.result === 'void' ? (fn.error ? `return nil, ${call}` : `${call}\n      return nil, nil`) : (fn.error ? `return ${call}` : `return ${call}, nil`);
    return `    ${JSON.stringify(fn.name)}: bind(${fn.params.length}, func(args []json.RawMessage) (any, error) {
${params}
      ${invoke}
    }),`;
  }).join('\n');
  return `// Code generated by wasmgen. DO NOT EDIT.
package main

import (
  "encoding/json"
  "fmt"
  "syscall/js"
  native ${JSON.stringify(importPath)}
)

type response struct {
  OK bool ${quote}json:"ok"${quote}
  Value any ${quote}json:"value,omitempty"${quote}
  Error string ${quote}json:"error,omitempty"${quote}
}

func encode(value any, err error) string {
  out := response{OK: err == nil, Value: value}
  if err != nil { out.Value = nil; out.Error = err.Error() }
  data, marshalErr := json.Marshal(out)
  if marshalErr != nil {
    // The error string itself is always JSON encodable.
    escaped, escapeErr := json.Marshal(marshalErr.Error())
    if escapeErr != nil { return ${quote}{"ok":false,"error":"cannot encode result"}${quote} }
    return ${quote}{"ok":false,"error":${quote} + string(escaped) + ${quote}}${quote}
  }
  return string(data)
}

func invoke(arity int, encoded string, call func([]json.RawMessage) (any, error)) (result string) {
  defer func() {
    if recovered := recover(); recovered != nil { result = encode(nil, fmt.Errorf("Go panic: %v", recovered)) }
  }()
  var args []json.RawMessage
  if err := json.Unmarshal([]byte(encoded), &args); err != nil { return encode(nil, fmt.Errorf("decode arguments: %w", err)) }
  if len(args) != arity { return encode(nil, fmt.Errorf("expected %d arguments", arity)) }
  value, err := call(args)
  return encode(value, err)
}

func bind(arity int, call func([]json.RawMessage) (any, error)) js.Func {
  return js.FuncOf(func(_ js.Value, values []js.Value) any {
    if len(values) != 1 || values[0].Type() != js.TypeString { return encode(nil, fmt.Errorf("expected encoded arguments")) }
    encoded := values[0].String()
    executor := js.FuncOf(func(_ js.Value, callbacks []js.Value) any {
      resolve := callbacks[0]
      // Return to JS before waiting for timers/channels: blocking a js.FuncOf
      // callback would prevent the event loop from resuming the Go scheduler.
      // The owning Worker bounds this goroutine's lifetime on abort/timeout.
      go func() { resolve.Invoke(invoke(arity, encoded, call)) }()
      return nil
    })
    promise := js.Global().Get("Promise").New(executor)
    // Promise constructors invoke their executor synchronously; keeping the
    // temporary js.Func beyond construction would leak one callback per call.
    executor.Release()
    return promise
  })
}

func main() {
  functions := map[string]js.Func{
${bindings}
  }
  api := js.Global().Get("Object").New()
  for name, fn := range functions { api.Set(name, fn) }
  js.Global().Set("__wasmgen_api", api)
  js.Global().Call("__wasmgen_ready")
  // The owning Web Worker keeps callbacks alive; dispose/abort terminates it
  // and releases its entire Go runtime, memory, and registered callbacks.
  select {}
}
`;
}
