import type { ResolvedInput } from '../../model/config.js';
import type { ResultType } from '../../model/value-types.js';

function cppType(type: ResultType): string {
  if (type.endsWith('[]')) return `std::vector<${cppType(type.slice(0, -2) as ResultType)}>`;
  return { i32: 'std::int32_t', u32: 'std::uint32_t', f64: 'double', bool: 'bool', string: 'std::string', void: 'void' }[type as Exclude<ResultType, `${string}[]`>];
}
export function cppBridge(mod: ResolvedInput): string {
  const functions = mod.exports.map((fn, index) => {
    const args = fn.params.map((param, i) => {
      if (!param.type.endsWith('[]')) return `    auto arg${i} = args[${i}].as<${cppType(param.type)}>();`;
      const scalar = cppType(param.type.slice(0, -2) as ResultType);
      return `    ${cppType(param.type)} arg${i};
    const auto size${i} = args[${i}]["length"].as<std::uint32_t>();
    arg${i}.reserve(size${i});
    for (std::uint32_t j = 0; j < size${i}; ++j) arg${i}.push_back(args[${i}][j].as<${scalar}>());`;
    }).join('\n');
    const call = `::${fn.symbol}(${fn.params.map((_, i) => `arg${i}`).join(', ')})`;
    let invoke;
    if (fn.result === 'void') invoke = `    ${call};\n    result.set("value", val::undefined());`;
    else if (fn.result.endsWith('[]')) invoke = `    const auto value = ${call};
    auto array = val::array();
    for (std::size_t i = 0; i < value.size(); ++i) array.set(static_cast<unsigned>(i), value[i]);
    result.set("value", array);`;
    else invoke = `    result.set("value", ${call});`;
    return `val call_${index}(val args) {
  auto result = val::object();
  try {
${args}
${invoke}
    result.set("ok", true);
  } catch (const std::exception& error) {
    result.set("ok", false);
    result.set("error", std::string(error.what()));
  } catch (...) {
    result.set("ok", false);
    result.set("error", std::string("unknown C++ exception"));
  }
  return result;
}`;
  }).join('\n\n');
  return `// Code generated by wasmgen. DO NOT EDIT.
#include <cstdint>
#include <exception>
#include <string>
#include <vector>
#include <emscripten/bind.h>
${mod.headers.map(header => header.includes('>') ? `#include "${header}"` : `#include <${header}>`).join('\n')}
namespace {
using emscripten::val;
${functions}
// Register inside this scope so global native overloads cannot hide wrappers.
EMSCRIPTEN_BINDINGS(wasmgen_module) {
${mod.exports.map((_, index) => `  emscripten::function("wasmgen_call_${index}", &call_${index});`).join('\n')}
}
}
`;
}
