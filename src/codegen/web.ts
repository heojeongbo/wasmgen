import type { ResolvedInput } from '../model/config.js';
import type { ResultType } from '../model/value-types.js';
import type { CompilerAdapter } from '../adapters/compiler.js';
import { copyFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const banner = '// Code generated by wasmgen. DO NOT EDIT.\n';
function ts(type: ResultType): string {
  if (type.endsWith('[]')) return `${ts(type.slice(0, -2) as ResultType)}[]`;
  return { i32: 'number', u32: 'number', f64: 'number', bool: 'boolean', string: 'string', void: 'void' }[type as Exclude<ResultType, `${string}[]`>];
}
export async function writeShared(output: string) {
  await copyFile(new URL('../../LICENSE', import.meta.url), path.join(output, 'WASMGEN-LICENSE'));
  await copyFile(new URL('../runtime/client.js', import.meta.url), path.join(output, 'client.js'));
  await copyFile(new URL('../runtime/worker.js', import.meta.url), path.join(output, 'worker-runtime.js'));
  await copyFile(new URL('../runtime/protocol.js', import.meta.url), path.join(output, 'protocol.js'));
}
export async function writeWeb(mod: ResolvedInput, directory: string, adapter: CompilerAdapter) {
  const methods = mod.exports.map((fn) => `    ${fn.name}: (...args) => client.call(${JSON.stringify(fn.name)}, args),`).join('\n');
  await writeFile(path.join(directory, 'index.js'), `${banner}import { connect } from '../client.js';
export async function create(options = {}) {
  const client = await connect(() => new Worker(new URL('./worker.js', import.meta.url), { type: 'module' }), options);
  return {
${methods}
    dispose: client.dispose,
  };
}
`);
  const signatures = mod.exports.map((fn) => `  ${fn.name}(${fn.params.map((p) => `${p.name}: ${ts(p.type)}`).join(', ')}): Promise<${ts(fn.result)}>;`).join('\n');
  await writeFile(path.join(directory, 'index.d.ts'), `${banner}export interface Options {
  /** Abort ends the worker and rejects every pending call. */
  signal?: AbortSignal;
  /** Initialization/call deadline in milliseconds; expiration ends the worker. Default: 30000. */
  timeoutMs?: number;
}
export interface API {
${signatures}
  /** Idempotent; terminates this instance and rejects pending calls. */
  dispose(): void;
}
export declare function create(options?: Options): Promise<API>;
`);
  const schema = Object.fromEntries(mod.exports.map(({ name, params, result }) => [name, { params, result }]));
  const initialize = adapter.workerSource();
  await writeFile(path.join(directory, 'worker.js'), `${banner}import { serve } from '../worker-runtime.js';\nconst schema = ${JSON.stringify(schema)};\n${initialize}\n`);
}
export async function writeBarrel(modules: ResolvedInput[], output: string) {
  const lines = modules.map((mod) => `export { create as ${mod.name} } from './${mod.name}/index.js';`);
  await writeFile(path.join(output, 'index.js'), banner + lines.join('\n') + '\n');
  await writeFile(path.join(output, 'index.d.ts'), banner + lines.join('\n') + '\n');
}
