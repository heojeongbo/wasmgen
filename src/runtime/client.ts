import { isResponse, type CallRequest } from './protocol.js';

export interface ClientOptions { signal?: AbortSignal; timeoutMs?: number }
export interface Client { call(method: string, args: unknown[]): Promise<unknown>; dispose(): void }
export interface WorkerPort {
  postMessage(message: CallRequest): void;
  terminate(): void;
  onerror: ((event: ErrorEvent) => void) | null;
  onmessageerror: (() => void) | null;
  onmessage: ((event: MessageEvent<unknown>) => void) | null;
}
interface Pending { resolve(value: unknown): void; reject(reason: unknown): void; timer: ReturnType<typeof setTimeout> }
